#Experiment 3: Gaussian Mixture Model using EM Algorithm

import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.mixture import GaussianMixture

#1. Generate Synthetic Dataset
X, y = make_blobs(n_samples=300, centers=3,
                  n_features=2, random_state=42)

#2. Initialize Parameters
k = 3
n, d = X.shape
np.random.seed(42)
weights = np.ones(k) / k
means = X[np.random.choice(n, k, replace=False)]
covariances = np.array([np.eye(d) for i in range(k)])

# Gaussian Probability Function
def gaussian(x, mean, cov):

    diff = x - mean
    cov = cov + 1e-6 * np.eye(d)
    exponent = -0.5 * np.sum(
        diff @ np.linalg.inv(cov) * diff, axis=1
    )

    denominator = np.sqrt(
        (2 * np.pi) ** d * np.linalg.det(cov)
    )

    return np.exp(exponent) / denominator

#3. EM Algorithm
for iteration in range(50):

    # E-Step: Calculate Responsibilities
    responsibility = np.zeros((n, k))

    for j in range(k):
        responsibility[:, j] = (
            weights[j] * gaussian(X, means[j], covariances[j])
        )

    responsibility = responsibility / (
        responsibility.sum(axis=1, keepdims=True) + 1e-10
    )

    # M-Step: Update Parameters
    Nk = responsibility.sum(axis=0)

    for j in range(k):

        weights[j] = Nk[j] / n

        means[j] = np.sum(
            responsibility[:, j, None] * X, axis=0
        ) / Nk[j]

        diff = X - means[j]

        covariances[j] = (
            (responsibility[:, j, None] * diff).T @ diff
        ) / Nk[j]

        covariances[j] += 1e-6 * np.eye(d)

    if iteration in [0, 4, 9, 19, 49]:
        print("Iteration:", iteration + 1)
        print("Means:\n", means)

#4. Predict Clusters
labels = np.argmax(responsibility, axis=1)

#5. Plot Gaussian Ellipses
def plot_ellipse(mean, cov, ax):

    eigenvalues, eigenvectors = np.linalg.eigh(cov)

    angle = np.degrees(
        np.arctan2(eigenvectors[1, 0],
                   eigenvectors[0, 0])
    )
    width, height = 2 * 2 * np.sqrt(eigenvalues)

    from matplotlib.patches import Ellipse

    ellipse = Ellipse(
        mean, width, height,
        angle=angle, fill=False, linewidth=2
    )
    ax.add_patch(ellipse)


fig, axes = plt.subplots(1, 2, figsize=(12, 5))

axes[0].scatter(X[:, 0], X[:, 1], c=y)
axes[0].set_title("Original Dataset")
axes[1].scatter(X[:, 0], X[:, 1], c=labels)

for j in range(k):
    plot_ellipse(means[j], covariances[j], axes[1])

axes[1].set_title("GMM Clustering using EM")
plt.show()

#6. Compare with Sklearn GMM
model = GaussianMixture(n_components=3, random_state=42)

model.fit(X)

sklearn_labels = model.predict(X)
plt.figure(figsize=(6, 5))
plt.scatter(X[:, 0], X[:, 1], c=sklearn_labels)
plt.title("Sklearn Gaussian Mixture Model")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.show()

print("\nSklearn GMM Means:")
print(model.means_)
print("\nOur EM Means:")
print(means)