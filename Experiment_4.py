#Experiment 4: Principal Component Analysis (PCA)

import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import load_wine
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA


#1. Load Wine Dataset
data = load_wine()
X = data.data
y = data.target
print("Original Dataset Shape:", X.shape)

#2. Standardize the Data
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

#3. PCA From Scratch
mean = np.mean(X_scaled, axis=0)
X_centered = X_scaled - mean
cov_matrix = np.cov(X_centered, rowvar=False)
eigenvalues, eigenvectors = np.linalg.eigh(cov_matrix)
idx = np.argsort(eigenvalues)[::-1]

eigenvalues = eigenvalues[idx]
eigenvectors = eigenvectors[:, idx]
components = eigenvectors[:, :2]
X_pca = np.dot(X_centered, components)
print("\nReduced Dataset Shape:", X_pca.shape)

# 4. Visualize PCA Results
plt.figure(figsize=(7, 5))
plt.scatter(X_pca[:, 0], X_pca[:, 1], c=y)
plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.title("PCA From Scratch")
plt.colorbar(label="Wine Classes")
plt.show()

#5. Reconstruct Original Data
X_reconstructed = np.dot(X_pca, components.T)
error = np.mean((X_centered - X_reconstructed) ** 2)
print("\nReconstruction Error:", error)

# 6. Calculate Explained Variance Ratio
variance_ratio = eigenvalues / np.sum(eigenvalues)
print("\nExplained Variance Ratio:")
print(variance_ratio[:2])
print("\nTotal Variance Explained:",
      np.sum(variance_ratio[:2]) * 100, "%")

# 7. PCA Using Sklearn
pca = PCA(n_components=2)
X_sklearn = pca.fit_transform(X_scaled)
print("\nSklearn PCA Shape:", X_sklearn.shape)
print("\nSklearn Explained Variance Ratio:")
print(pca.explained_variance_ratio_)

#8. Compare Both PCA Results
plt.figure(figsize=(12, 5))
plt.subplot(1, 2, 1)
plt.scatter(X_pca[:, 0], X_pca[:, 1], c=y)
plt.title("PCA From Scratch")
plt.xlabel("PC1")
plt.ylabel("PC2")
plt.subplot(1, 2, 2)
plt.scatter(X_sklearn[:, 0], X_sklearn[:, 1], c=y)
plt.title("PCA Using Sklearn")
plt.xlabel("PC1")
plt.ylabel("PC2")
plt.tight_layout()
plt.show()

#9. Plot Explained Variance
plt.figure(figsize=(7, 5))
plt.plot(
    range(1, len(variance_ratio) + 1),
    np.cumsum(variance_ratio),
    marker='o'
)

plt.xlabel("Number of Principal Components")
plt.ylabel("Cumulative Explained Variance")
plt.title("Explained Variance by PCA")
plt.grid()
plt.show()